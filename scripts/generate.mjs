// Generates the derived files from the sources in brands/ and system/:
//  - brands/<id>/tokens.css  CSS variables for every mode
//  - brands/<id>/brief.md    the whole brand resolved into one file (overrides applied)
//  - llms.txt                only the block between the GENERATED markers
// These are committed so agents reading the repo see them. `npm run check` fails if they are stale.
import StyleDictionary from 'style-dictionary';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, read, loadAll, flattenTokens, KINDS, fontHref, iconSets } from './lib/brands.mjs';

const GENERATED = (sources) =>
  `GENERATED by scripts/generate.mjs from ${sources}. Do not edit this file: edit the sources, then run \`npm run generate\`.`;

async function cssVariables(tokens, selector) {
  const sd = new StyleDictionary({
    tokens,
    platforms: {
      css: {
        transformGroup: 'css',
        files: [{ destination: 'x.css', format: 'css/variables', options: { selector, showFileHeader: false, outputReferences: false } }],
      },
    },
    log: { verbosity: 'silent' },
  });
  const [file] = await sd.formatPlatform('css');
  return file.output.trim();
}

const indent = (s) => s.split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');

async function tokensCss(brand) {
  const parts = [`/* ${GENERATED(`${brand.dir}/tokens*.json`)} */`, await cssVariables(brand.tokens, ':root, :host')];
  for (const { mode, tokens } of brand.modes) {
    parts.push(`/* Mode: ${mode}. Set data-mode="${mode}" on <html> or any container. */`);
    parts.push(await cssVariables(tokens, `[data-mode="${mode}"], :host([data-mode="${mode}"])`));
    if (mode === 'dark') {
      parts.push('/* Follow the OS setting when no data-mode is set. */');
      parts.push(`@media (prefers-color-scheme: dark) {\n${indent(await cssVariables(tokens, ':root:not([data-mode]), :host(:not([data-mode]))'))}\n}`);
    }
  }
  return parts.join('\n\n') + '\n';
}

// Push markdown headings down `by` levels, leaving code fences alone.
function shiftHeadings(md, by) {
  let fence = null;
  return md.split('\n').map((line) => {
    const f = line.match(/^(`{3,})/);
    if (f) fence = fence ? (line.startsWith(fence) ? null : fence) : f[1];
    return !fence && /^#{1,6} /.test(line) ? '#'.repeat(by) + line : line;
  }).join('\n').trim();
}

const iconList = (meta) => {
  const sets = iconSets(meta);
  if (!sets.length) return 'Not specified.';
  if (sets.length === 1 && !sets[0].use) return sets[0].name;
  return sets.map((s) => [
    `- **${s.name}**${s.use ? ` — ${s.use}` : ''}`,
    s.source ? `  Source: ${s.source}` : '',
    s.files ? `  Files: \`${s.files}\`` : '',
  ].filter(Boolean).join('\n')).join('\n');
};

const tokenList = (tokens) =>
  flattenTokens(tokens).map((t) => `- \`--${t.name}\`: \`${t.value}\`${t.description ? ` — ${t.description}` : ''}`).join('\n');

function brief(brand, css) {
  const m = brand.meta;
  const origin = (d) => ({
    shared: `Shared component (\`${d.path}\`).`,
    override: `Brand override (\`${d.path}\`), replaces \`${d.replaces}\`.`,
    brand: `${m.name}-only (\`${d.path}\`).`,
  })[d.origin];
  const docs = (kind, label) => {
    const items = brand[kind];
    if (!items.length) return `## ${label}\n\nNone.`;
    return `## ${label}\n\n` + items.map((d) => [
      `### ${d.data.title ?? d.name}`,
      `${d.data.summary ? d.data.summary + ' ' : ''}${origin(d)}${d.data.uses?.length ? ` Also needs the CSS from: ${d.data.uses.join(', ')}.` : ''}`,
      shiftHeadings(d.body, 2),
    ].join('\n\n')).join('\n\n');
  };
  const assets = brand.assetsDoc
    ? shiftHeadings(brand.assetsDoc.body, 1).replace(/\]\(\.?\/?(?!https?:)([^)]+)\)/g, '](assets/$1)')
    : 'None.';

  return `<!-- ${GENERATED(`${brand.dir}/ and system/`)} -->

# ${m.name}: resolved brand brief

${m.summary ?? ''}

This file is the whole ${m.name} brand in one place, with shared components and ${m.name}'s overrides already merged. Use it to build or review anything for ${m.name}. Follow it exactly.

## Setup

1. Load the fonts:
${(m.fonts ?? []).map((u) => `   \`<link rel="stylesheet" href="${fontHref(brand, u)}">\``).join('\n') || '   (none)'}
2. Load the variables: \`brands/${brand.id}/tokens.css\` (copy also at the end of this file).
3. Load the base element styles: \`${brand.base}\`.
4. Copy the CSS of each component you use from the Components section. Use only the CSS variables, never raw colours or font names.
${brand.modes.length ? `5. Modes available: ${brand.modes.map((x) => `\`${x.mode}\``).join(', ')}. Set \`data-mode="<mode>"\` on \`<html>\`; dark also follows the OS setting when no data-mode is set. Check your output in every mode.\n` : ''}
## Icons

${iconList(m)}

## Guidelines

${shiftHeadings(brand.guidelines.body, 1)}

## Tokens

${Object.keys(brand.tokens)
  .filter((g) => !g.startsWith('$'))
  .map((g) => `### ${g}\n\n${tokenList({ [g]: brand.tokens[g] })}`).join('\n\n')}
${brand.modes.map((x) => `\n### ${x.mode} mode overrides\n\n${tokenList(x.tokens)}`).join('\n')}

## Assets

${assets}

${docs('components', 'Components')}${brand.excluded.length ? `\n\nNot available for ${m.name} (excluded on purpose, don't build them): ${brand.excluded.join(', ')}.` : ''}

${docs('patterns', 'Patterns')}

## Base styles (\`${brand.base}\`)

\`\`\`css
${read(brand.base).trim()}
\`\`\`

## CSS variables (\`brands/${brand.id}/tokens.css\`)

\`\`\`css
${css.trim()}
\`\`\`
`;
}

const BEGIN = '<!-- BEGIN GENERATED: npm run generate -->';
const END = '<!-- END GENERATED -->';

function llmsIndex(current, { system, brands }) {
  const block = [
    BEGIN,
    '## Brands',
    '',
    ...brands.map((b) => `- **${b.meta.name}** — ${b.meta.summary ?? ''}\n  Start with \`brands/${b.id}/brief.md\`. Source folder: \`brands/${b.id}/\`.`),
    '',
    '## Shared components',
    '',
    ...KINDS.flatMap((k) => system[k].map((d) => `- \`${d.path}\` — ${d.data.summary ?? d.data.title ?? d.name}`)),
    END,
  ].join('\n');
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < 0) throw new Error(`llms.txt is missing the ${BEGIN} / ${END} markers`);
  return current.slice(0, start) + block + current.slice(end + END.length);
}

// Returns { relativePath: content } for every generated file.
export async function buildOutputs(all = loadAll()) {
  const out = {};
  for (const b of all.brands) {
    const css = await tokensCss(b);
    out[`${b.dir}/tokens.css`] = css;
    out[`${b.dir}/brief.md`] = brief(b, css);
  }
  out['llms.txt'] = llmsIndex(read('llms.txt'), all);
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = await buildOutputs();
  for (const [p, content] of Object.entries(out)) writeFileSync(join(ROOT, p), content);
  console.log(`Generated: ${Object.keys(out).join(', ')}`);
}
