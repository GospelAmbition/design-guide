// Generates the derived files from the sources in brands/ and system/:
//  - brands/<id>/tokens.css  CSS variables for every mode
//  - brands/<id>/brand.css   everything a page links: reset, tokens, base, composition, components,
//                            patterns, utilities and surfaces, as cascade layers
//  - brands/<id>/brief.md    the whole brand resolved into one file (overrides applied)
//  - brands/<id>/kit.json    what scripts/new-page.mjs copies into a new page: fonts and the assets brand.css uses
//  - llms.txt                only the block between the GENERATED markers
// These are committed so agents reading the repo see them. `npm run check` fails if they are stale.
import StyleDictionary from 'style-dictionary';
import { writeFileSync, existsSync } from 'node:fs';
import { join, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, read, loadAll, flattenTokens, resolvedTokens, KINDS, isUrl, iconSets } from './lib/brands.mjs';
import { brandCss, utilityRules, surfaces } from './lib/brand-css.mjs';
import { coloursIn, parseColour, contrast, over, parseCss } from './lib/css.mjs';

const GENERATED = (sources) =>
  `GENERATED by scripts/generate.mjs from ${sources}. Do not edit this file: edit the sources, then run \`npm run generate\`.`;

async function cssVariables(tokens, selector) {
  const sd = new StyleDictionary({
    tokens,
    platforms: {
      css: {
        transformGroup: 'css',
        files: [{ destination: 'x.css', format: 'css/variables', options: { selector, showFileHeader: false, outputReferences: false } }],
      },
    },
    log: { verbosity: 'silent' },
  });
  const [file] = await sd.formatPlatform('css');
  return file.output.trim();
}

const indent = (s) => s.split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');

async function tokensCss(brand) {
  const parts = [`/* ${GENERATED(`${brand.dir}/tokens*.json`)} */`, await cssVariables(brand.tokens, ':root, :host')];
  for (const { mode, tokens } of brand.modes) {
    parts.push(`/* Mode: ${mode}. Set data-mode="${mode}" on <html> or any container. */`);
    parts.push(await cssVariables(tokens, `[data-mode="${mode}"], :host([data-mode="${mode}"])`));
    if (mode === 'dark') {
      parts.push('/* Follow the OS setting when no data-mode is set. */');
      parts.push(`@media (prefers-color-scheme: dark) {\n${indent(await cssVariables(tokens, ':root:not([data-mode]), :host(:not([data-mode]))'))}\n}`);
    }
  }
  return parts.join('\n\n') + '\n';
}

// Push markdown headings down `by` levels, leaving code fences alone.
function shiftHeadings(md, by) {
  let fence = null;
  return md.split('\n').map((line) => {
    const f = line.match(/^(`{3,})/);
    if (f) fence = fence ? (line.startsWith(fence) ? null : fence) : f[1];
    return !fence && /^#{1,6} /.test(line) ? '#'.repeat(by) + line : line;
  }).join('\n').trim();
}

const iconList = (meta) => {
  const sets = iconSets(meta);
  if (!sets.length) return 'Not specified.';
  if (sets.length === 1 && !sets[0].use) return sets[0].name;
  return sets.map((s) => [
    `- **${s.name}**${s.use ? ` — ${s.use}` : ''}`,
    s.source ? `  Source: ${s.source}` : '',
    s.files ? `  Files: \`${s.files}\`` : '',
  ].filter(Boolean).join('\n')).join('\n');
};

const tokenList = (tokens) =>
  flattenTokens(tokens).map((t) => `- \`--${t.name}\`: \`${t.value}\`${t.description ? ` — ${t.description}` : ''}`).join('\n');

// The weakest contrast of a surface role against its background (every stop, for a gradient).
export function surfaceContrast(brand, surface, role) {
  const t = resolvedTokens(brand.tokens);
  const white = [255, 255, 255, 1];
  const bgs = coloursIn(t[`surface.${surface}.background`] ?? '').filter((c) => c[3] > 0).map((c) => over(c, white));
  const fg = parseColour(t[`surface.${surface}.${role}`] ?? '');
  if (!bgs.length || !fg) return null;
  return Math.min(...bgs.map((bg) => contrast(over(fg, bg), bg)));
}

function utilitiesSection(brand) {
  const rules = utilityRules(brand);
  const groups = [...new Set(rules.map((r) => r.group))];
  return groups.map((g) => {
    const rs = rules.filter((r) => r.group === g);
    const decl = (r) => Object.entries(r.decls).map(([p, v]) => `${p}: ${v}`).join('; ');
    return `- ${rs[0].description ?? g}: ${rs.map((r) => `\`.${r.cls}\``).join(', ')}${rs.length === 1 ? ` (\`${decl(rs[0])}\`)` : ` (e.g. \`.${rs[0].cls}\` is \`${decl(rs[0])}\`)`}`;
  }).join('\n');
}

function surfacesSection(brand) {
  const list = surfaces(brand);
  if (!list.length) return 'None defined.';
  return list.map(({ name, description, roles }) => {
    const ratios = roles.filter((r) => r !== 'background').map((r) => {
      const c = surfaceContrast(brand, name, r);
      return `${r} ${c ? c.toFixed(1) + ':1' : 'n/a'}`;
    });
    return `- \`.surface-${name}\`${description ? ` — ${description}` : ''} Contrast on it: ${ratios.join(', ')}.`;
  }).join('\n');
}

// Single-class rules in the base styles (.lead, .eyebrow, …): text styles any page may use.
function textStylesSection(brand) {
  const rules = parseCss(read(brand.base)).filter((n) => n.type === 'rule' && /^\.[\w-]+$/.test(n.selector));
  if (!rules.length) return 'None. Headings and body text are styled by element.';
  return rules.map((r) => `- \`${r.selector}\`: \`${r.decls.map((d) => `${d.prop}: ${d.value}`).join('; ')}\``).join('\n');
}

// Components and patterns are shown without their CSS: it is all in brand.css, and agents copy what they see.
const withoutCss = (body) => body.replace(/^(`{3,})css[^\n]*\n[\s\S]*?\n\1[ \t]*$/gm, '').replace(/\n{3,}/g, '\n\n');

function brief(brand, css) {
  const m = brand.meta;
  const origin = (d) => ({
    shared: `Shared (\`${d.path}\`).`,
    override: `Brand override (\`${d.path}\`), replaces \`${d.replaces}\`.`,
    brand: `${m.name}-only (\`${d.path}\`).`,
  })[d.origin];
  const docs = (kind, label) => {
    const items = brand[kind];
    if (!items.length) return `## ${label}\n\nNone.`;
    const showCss = kind === 'composition';
    return `## ${label}\n\n` + items.map((d) => [
      `### ${d.data.title ?? d.name}`,
      `${d.data.summary ? d.data.summary + ' ' : ''}${origin(d)}${d.data.uses?.length ? ` Works with: ${d.data.uses.join(', ')}.` : ''}${showCss ? '' : ` Its CSS is in brand.css (look for \`/* ${d.path} */\`).`}`,
      shiftHeadings(showCss ? d.body : withoutCss(d.body), 2),
    ].join('\n\n')).join('\n\n');
  };
  const assets = brand.assetsDoc
    ? shiftHeadings(brand.assetsDoc.body, 1).replace(/\]\(\.?\/?(?!https?:)([^)]+)\)/g, '](assets/$1)')
    : 'None.';

  return `<!-- ${GENERATED(`${brand.dir}/ and system/`)} -->

# ${m.name}: resolved brand brief

${m.summary ?? ''}

> **Building a page?** Read [\`build-a-page.md\`](../../build-a-page.md) first and follow its steps. This brief is the reference it points you to.

This file is the whole ${m.name} brand in one place, with shared composition, components and patterns and ${m.name}'s overrides already merged. Use it to build or review anything for ${m.name}. Follow it exactly.

## Setup

1. Load the fonts:
${(m.fonts ?? []).map((u) => `   \`<link rel="stylesheet" href="${isUrl(u) ? u : u.replace(/^\.?\//, '')}">\``).join('\n') || '   (none)'}
2. Link \`brands/${brand.id}/brand.css\`. It holds everything below as CSS, in CUBE CSS order: reset, tokens, base, composition, components, patterns, utilities and surfaces.
3. Link the page's own \`site.css\` after it, for anything the brand doesn't cover.
4. Copy the **HTML** of the examples below and change only the content. Their CSS is already in brand.css: components and patterns are listed here without it, and layout primitives show theirs only so you can see what each setting does. Never copy CSS into a page.
${brand.modes.length ? `5. Modes available: ${brand.modes.map((x) => `\`${x.mode}\``).join(', ')}. Set \`data-mode="<mode>"\` on \`<html>\`; dark also follows the OS setting when no data-mode is set. Check your output in every mode.\n` : ''}
## How to style anything (CUBE CSS)

Reach for these in order, and stop at the first that works:

1. **A pattern** below, as it is.
2. **A pattern or component plus utilities, surfaces and settings**: \`class="… py-xl surface-dark"\`, \`style="--gutter: var(--space-s)"\`.
3. **Composition primitives** (flow, cluster, switcher, sidebar, grid, …) holding **components**.
4. **A new block in site.css**, built only from tokens, with a comment saying why 1–3 didn't work.

Variants are exceptions written as data attributes on the block (\`class="btn" data-variant="primary"\`); states use ARIA or \`data-state\`. Inline styles may only set a primitive's or component's settings (the custom properties in its Settings table) to tokens. No media queries: layouts respond to their container.

## Utilities

Generated from the tokens. One class, one job.

${utilitiesSection(brand)}

## Text styles

Classes from the base styles for text that isn't a plain heading or paragraph. Use them anywhere, including to give a heading the look of another level.

${textStylesSection(brand)}

## Surfaces

A surface sets a background with the text and link colours that pass contrast on it. Put sections and boxes on a surface instead of picking colours one by one.

${surfacesSection(brand)}

## Icons

${iconList(m)}

## Guidelines

${shiftHeadings(brand.guidelines.body, 1)}

## Tokens

${Object.keys(brand.tokens)
  .filter((g) => !g.startsWith('$'))
  .map((g) => `### ${g}\n\n${tokenList({ [g]: brand.tokens[g] })}`).join('\n\n')}
${brand.modes.map((x) => `\n### ${x.mode} mode overrides\n\n${tokenList(x.tokens)}`).join('\n')}

## Assets

${assets}

${docs('composition', 'Composition')}

${docs('components', 'Components')}${brand.excluded.length ? `\n\nNot available for ${m.name} (excluded on purpose, don't build them): ${brand.excluded.join(', ')}.` : ''}

${docs('patterns', 'Patterns')}

## Base styles (\`${brand.base}\`)

\`\`\`css
${read(brand.base).trim()}
\`\`\`
`;
}

const BEGIN = '<!-- BEGIN GENERATED: npm run generate -->';
const END = '<!-- END GENERATED -->';

function llmsIndex(current, { system, brands }) {
  const block = [
    BEGIN,
    '## Brands',
    '',
    ...brands.map((b) => `- **${b.meta.name}** — ${b.meta.summary ?? ''}\n  Start with \`brands/${b.id}/brief.md\`. Stylesheet for pages: \`brands/${b.id}/brand.css\`. Source folder: \`brands/${b.id}/\`.`),
    '',
    ...KINDS.filter((k) => system[k].length).flatMap((k) => [
      `## Shared ${k}`,
      '',
      ...system[k].map((d) => `- \`${d.path}\` — ${d.data.summary ?? d.data.title ?? d.name}`),
      '',
    ]).slice(0, -1),
    END,
  ].join('\n');
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < 0) throw new Error(`llms.txt is missing the ${BEGIN} / ${END} markers`);
  return current.slice(0, start) + block + current.slice(end + END.length);
}

// Files a page needs next to brand.css: self-hosted font stylesheets with the files they load, and
// every asset brand.css itself points at. Paths are relative to the brand folder.
function kit(brand, css) {
  const fonts = (brand.meta.fonts ?? []).map((u) => (isUrl(u) ? u : u.replace(/^\.?\//, '')));
  const files = new Set();
  for (const f of fonts.filter((u) => !isUrl(u))) {
    files.add(f);
    const dir = f.includes('/') ? f.slice(0, f.lastIndexOf('/') + 1) : '';
    for (const [, , url] of read(`${brand.dir}/${f}`).matchAll(/url\(\s*(['"]?)(?!data:|https?:)([^'")?#]+)[^)]*\1\s*\)/g)) files.add(normalize(dir + url));
  }
  for (const [, , url] of css.matchAll(/url\(\s*(['"]?)(?!data:|https?:|\/)([^'")?#]+)[^)]*\1\s*\)/g)) files.add(url);
  const missing = [...files].filter((f) => !existsSync(join(ROOT, brand.dir, f)));
  if (missing.length) throw new Error(`${brand.dir}: brand.css or a font stylesheet points at missing files: ${missing.join(', ')}`);
  return JSON.stringify({ brand: brand.id, name: brand.meta.name, fonts, files: [...files].sort() }, null, 2) + '\n';
}

// Returns { relativePath: content } for every generated file.
export async function buildOutputs(all = loadAll()) {
  const out = {};
  for (const b of all.brands) {
    const css = await tokensCss(b);
    out[`${b.dir}/tokens.css`] = css;
    out[`${b.dir}/brand.css`] = brandCss(b, css);
    out[`${b.dir}/kit.json`] = kit(b, out[`${b.dir}/brand.css`]);
    out[`${b.dir}/brief.md`] = brief(b, css);
  }
  out['llms.txt'] = llmsIndex(read('llms.txt'), all);
  return out;
}

