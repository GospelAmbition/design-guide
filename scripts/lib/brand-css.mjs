// Builds brands/<id>/brand.css: everything a page needs from the brand in one stylesheet, in CUBE CSS
// order as cascade layers. A page links it and adds its own site.css, which is unlayered and so always
// wins without specificity fights. Also used by the docs site so previews render with exactly this CSS.
import { read, fences, flattenTokens } from './brands.mjs';

export const LAYERS = ['reset', 'tokens', 'base', 'composition', 'components', 'patterns', 'utilities'];

const indent = (s) => s.split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');
const block = (name, body) => `@layer ${name} {\n${indent(body.trim())}\n}`;

// Utility classes from system/utilities.json plus the brand's utilities.json: [{ cls, decls, description, group }]
export function utilityRules(brand) {
  const out = [];
  for (const u of brand.utilities) {
    if (u.class) {
      out.push({ cls: u.class, decls: u.declarations, description: u.description, group: u.name });
    } else if (u.values) {
      for (const [suffix, value] of Object.entries(u.values)) out.push({ cls: `${u.name}-${suffix}`, decls: { [u.property]: value }, description: u.description, group: u.name });
    } else if (u.tokens) {
      const paths = Array.isArray(u.tokens) ? u.tokens : null;
      const group = paths ? null : u.tokens;
      const tokens = paths
        ? paths.map((p) => {
            const name = p.replace(/\./g, '-');
            return { name, suffix: p.split('.').slice(1).join('-') };
          })
        : brand.tokens[group]
          ? flattenTokens(brand.tokens[group], [group]).map((t) => ({ name: t.name, suffix: t.name.slice(group.length + 1) }))
          : [];
      for (const t of tokens) out.push({ cls: `${u.name}-${t.suffix}`, decls: { [u.property]: `var(--${t.name})` }, description: u.description, group: u.name });
    }
  }
  return out;
}

// Surfaces: tokens under `surface.<name>` with a background and the colours that go on it.
export function surfaces(brand) {
  return Object.entries(brand.tokens.surface ?? {})
    .filter(([k]) => !k.startsWith('$'))
    .map(([name, roles]) => ({
      name,
      description: roles.$description ?? '',
      roles: Object.keys(roles).filter((k) => !k.startsWith('$')),
    }));
}

export function surfaceRules(brand) {
  return surfaces(brand).flatMap(({ name, roles }) => {
    const v = (role) => `var(--surface-${name}-${role})`;
    // Set only the colour or only the image, so a block's own background image or colour survives.
    const prop = brand.tokens.surface[name].background?.$type === 'gradient' ? 'background-image' : 'background-color';
    const rules = [`.surface-${name} { ${prop}: ${v('background')}; color: ${v('text')}; }`];
    if (roles.includes('link')) rules.push(`.surface-${name} :where(a:not([class])) { color: ${v('link')}; }`);
    return rules;
  });
}

const docCss = (d) => fences(d.body).filter((f) => f.lang === 'css').map((f) => f.code.trim()).join('\n');

// `preview`: { assetBase } rewrites asset URLs for the docs site and makes `body` rules style the
// preview canvas instead (the canvas plays the body's role in a preview).
export function brandCss(brand, tokensCss, { preview = null } = {}) {
  const sources = (kind) =>
    brand[kind].map((d) => {
      const css = docCss(d);
      return css ? `/* ${d.path} */\n${css}` : '';
    }).filter(Boolean).join('\n\n');
  let base = read(brand.base).trim();
  if (preview) base = base.replace(/(?<![-\w.#])body(?![-\w])/g, '.canvas');
  const utilities = utilityRules(brand).map(({ cls, decls }) => `.${cls} { ${Object.entries(decls).map(([p, v]) => `${p}: ${v};`).join(' ')} }`);
  const parts = [
    `/* GENERATED by scripts/generate.mjs from ${brand.dir}/ and system/. brand: ${brand.id}
   Link this file from every page, after the brand's fonts and before the page's own site.css.
   Never edit it, in the design system or in a page: it is regenerated, and the page checker
   compares it with the design system's copy. Layers, lowest priority first: ${LAYERS.join(', ')}. */`,
    `@layer ${LAYERS.join(', ')};`,
    `/* --gutter doesn't inherit, so a gap set on one layout primitive never leaks into the primitives nested inside it. */
@property --gutter { syntax: "*"; inherits: false; }`,
    block('reset', read('system/reset.css').replace(/^\/\*[\s\S]*?\*\/\s*/, '')),
    block('tokens', tokensCss.replace(/^\/\*[\s\S]*?\*\/\s*/, '')),
    block('base', base),
    block('composition', sources('composition')),
    block('components', sources('components')),
    block('patterns', sources('patterns') || '/* none */'),
    block('utilities', [...utilities, '', '/* Surfaces: a background with the text and link colours that pass contrast on it. */', ...surfaceRules(brand)].join('\n')),
  ];
  let css = parts.join('\n\n') + '\n';
  // Brand sources link assets from the repo root (/brands/<id>/assets/…). brand.css sits in the brand
  // folder, and a page copies the assets it uses next to it, so the same relative path works in both.
  css = css.replace(new RegExp(`(url\\(\\s*["']?)/brands/${brand.id}/`, 'g'), '$1');
  if (preview) css = css.replace(/(url\(\s*["']?)(?!data:|https?:|\/)(assets\/)/g, `$1${preview.assetBase}$2`);
  return css;
}
